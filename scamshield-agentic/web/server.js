'use strict';
require('dotenv').config();
const path=require('node:path');
const express=require('express');
const helmet=require('helmet');
const rateLimit=require('express-rate-limit');
const {investigate,validate}=require('./engine');
const app=express();
const PORT=Number(process.env.PORT)||8787;
app.disable('x-powered-by');
app.use(helmet({contentSecurityPolicy:false,crossOriginEmbedderPolicy:false}));
app.use(express.json({limit:'12kb'}));
const origins=(process.env.CORS_ORIGINS||'').split(',').map(s=>s.trim()).filter(Boolean);
app.use((req,res,next)=>{const origin=req.headers.origin;if(origin&&(origins.includes('*')||origins.includes(origin))){res.setHeader('Access-Control-Allow-Origin',origin);res.setHeader('Vary','Origin');res.setHeader('Access-Control-Allow-Headers','Content-Type, Authorization');res.setHeader('Access-Control-Allow-Methods','GET,POST,OPTIONS');}if(req.method==='OPTIONS')return res.sendStatus(204);next();});
app.use('/api/',rateLimit({windowMs:60_000,limit:30,standardHeaders:true,legacyHeaders:false}));
app.get('/api/health',(req,res)=>res.json({ok:true,service:'ScamShield AI',version:'0.2.0',engine:'multi-stage agent orchestrator',llmConfigured:!!process.env.LLM_API_KEY&&process.env.ALLOW_MESSAGE_TO_LLM==='true',messageSharingEnabled:process.env.ALLOW_MESSAGE_TO_LLM==='true',urlReputation:'not-configured'}));
app.post('/api/investigations',async(req,res)=>{try{const {inputType,content,interacted}=req.body||{};const error=validate(inputType,content);if(error)return res.status(400).json({error});const report=await investigate({inputType,content,interacted:!!interacted});res.json(report);}catch(e){console.error('Investigation failed:',e.message);res.status(500).json({error:'Investigation failed. No reliable result was produced.'});}});
app.use(express.static(path.join(__dirname,'public'),{extensions:['html']}));
app.get('*',(req,res)=>res.sendFile(path.join(__dirname,'public','index.html')));
app.listen(PORT,'0.0.0.0',()=>console.log(`ScamShield AI web demo listening on http://localhost:${PORT}`));
